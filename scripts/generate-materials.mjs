import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = process.cwd();

const materials = {
  "welcome-material": "fvh-welcome.html",
  "lesson-1-material": "lesson-1.html",
  "lesson-2-material": "lesson-2.html",
  "lesson-3-material": "lesson-3.html",
  "lesson-4-material": "lesson-4.html",
  "lesson-5-material": "lesson-5.html",
  "lesson-6-material": "lesson-6.html",
  "lesson-7-material": "lesson-7.html",
  "lesson-8-material": "lesson-8.html",
  "lesson-9-material": "lesson-9.html",
  "lesson-10-material": "lesson-10.html",
  "lesson-11-material": "lesson-11.html",
  "lesson-12-material": "lesson-12.html",
  "lesson-13-material": "lesson-13.html",
  "lesson-14-material": "lesson-14.html",
  "lesson-15-material": "lesson-15.html",
  "closing-material": "fvh-closing.html",
};

const entries = Object.entries(materials).map(([id, filename]) => {
  const filePath = resolve(root, "src/course-materials", filename);
  const content = readFileSync(filePath, "utf8");

  return `  ${JSON.stringify(id)}: ${JSON.stringify(content)},`;
});

const output = `// This file is generated by scripts/generate-course-materials.mjs.
// Do not edit manually.

export const courseMaterials: Record<string, string> = {
${entries.join("\n")}
};
`;

writeFileSync(resolve(root, "src/course-data/materials.generated.ts"), output);
console.log("Generated src/course-data/materials.generated.ts");